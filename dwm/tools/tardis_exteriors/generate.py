#!/usr/bin/env python3
"""Generate the 2005 / 2010 / 2014 / 2018 TARDIS exterior meshes and textures.

Stdlib only and deterministic. Writes, per era:
  src/client/resources/assets/dwm/models/entity/tardis_<year>.json
  src/client/resources/assets/dwm/textures/entity/tardis_<year>.png

Layout:
  eras.py     per-era design spec (colours, weathering, posts, signs, roof, lamp, glazing, badge)
  geometry.py shared police-box geometry built from the spec, on a one-pixel grid
  uvpack.py   vanilla box-UV nets, shelf-packed; identical cube + paint pairs share a net
  paint.py    per-face painters (flat mottled paint, glass, sign lettering, notice, badge, lamp)
  preview.py  offline preview renderer, optionally beside the older boxes (scratch output, not shipped)

Contract with the game (see TardisModel / TardisChameleonVariant):
  * root parts `LeftDoor` (hinge x=+5, the leaf that swings) and `rightDoor`, bound by
    `door_progress * 60`; nothing that belongs to the shell is parented under a door;
  * the closed leaves exactly fill the BOTI aperture x -5..5, height 1..23 at z -5.5.

Run from the repo root:  python3 dwm/tools/tardis_exteriors/generate.py
"""
from __future__ import annotations

import json
import struct
import sys
import zlib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from eras import ERAS, Era  # noqa: E402
from geometry import parts  # noqa: E402
from paint import Painter  # noqa: E402
from uvpack import Packer, face_rects  # noqa: E402

UV = 128  # declared texture_width / texture_height
PX = 4  # pixels per UV unit in the PNG (matches the 2nd-7th Doctor boxes)

ROOT = Path(__file__).resolve().parents[2]
MODEL_DIR = ROOT / "src/client/resources/assets/dwm/models/entity"
TEXTURE_DIR = ROOT / "src/client/resources/assets/dwm/textures/entity"


def r3(v: float) -> float:
    v = round(v, 3)
    return 0.0 if v == 0 else v


def build(era: Era):
    """Returns (model json, RGBA pixel rows)."""
    part_specs = parts(era)
    packer = Packer(UV)
    for spec in part_specs:
        for b in spec["boxes"]:
            packer.request(b.key(), *b.size)
    packer.pack()

    img = [[(0, 0, 0, 0)] * (UV * PX) for _ in range(UV * PX)]
    painter = Painter(era, img)
    for key, (u, v) in sorted(packer.slots.items(), key=lambda kv: kv[1]):
        w, h, d, roles = key
        rects = face_rects(u, v, w, h, d)
        for face, role in roles:
            fu, fv, fw, fh = rects[face]
            px = (round(fu * PX), round(fv * PX), round(fw * PX), round(fh * PX))
            if px[2] < 1 or px[3] < 1:
                raise ValueError(f"{face} face of a {w}x{h}x{d} cube is thinner than a texture pixel")
            painter.paint(role, px, face)

    json_parts = []
    for spec in part_specs:
        ox, oy, oz = spec.get("pivot", (0.0, 24.0, 0.0))
        cubes = []
        for b in spec["boxes"]:
            u, v = packer.slot(b.key())
            w, h, d = b.size
            cubes.append({"uv": [u, v],
                          "origin": [r3(b.x0 - ox), r3((24.0 - b.h1) - oy), r3(b.z0 - oz)],
                          "size": [r3(w), r3(h), r3(d)]})
        part = {"name": spec["name"], "pivot": [ox, oy, oz]}
        if "rotation" in spec:
            part["rotation"] = list(spec["rotation"])
        part["cubes"] = cubes
        json_parts.append(part)

    model = {
        "credit": f"Generated by dwm/tools/tardis_exteriors/generate.py ({era.year} TARDIS exterior)",
        "texture_width": UV,
        "texture_height": UV,
        "texture": f"dwm:textures/entity/{era.id}.png",
        "parts": json_parts,
        "animation": {"bindings": [{"part": "LeftDoor", "channel": "rot_y", "value": "door_progress * 60"}]},
    }
    return model, img


def png_bytes(pixels) -> bytes:
    h, w = len(pixels), len(pixels[0])
    raw = b"".join(b"\x00" + b"".join(struct.pack("4B", *px) for px in row) for row in pixels)

    def chunk(tag, data):
        body = tag + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body) & 0xFFFFFFFF)

    return (b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(raw, 9))
            + chunk(b"IEND", b""))


def main():
    MODEL_DIR.mkdir(parents=True, exist_ok=True)
    TEXTURE_DIR.mkdir(parents=True, exist_ok=True)
    for era in ERAS:
        model, img = build(era)
        (MODEL_DIR / f"{era.id}.json").write_text(json.dumps(model, indent=2) + "\n")
        (TEXTURE_DIR / f"{era.id}.png").write_bytes(png_bytes(img))
        cubes = sum(len(p["cubes"]) for p in model["parts"])
        print(f"wrote {era.id}: {cubes} cubes")


if __name__ == "__main__":
    main()
